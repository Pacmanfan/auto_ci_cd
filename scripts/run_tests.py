#!/usr/bin/env python3
"""Tiered, affected-test execution (REQ-DEVOPS-046, ADR-000186).

    python3 scripts/run_tests.py [--tier t0|t1|t2|t3|perf|stress|soak|live|package]
                                 [--request <request file> | --base <ref> | --paths P ... | --all]
                                 [--suite ID ...] [--build-dir DIR] [--jobs N]
                                 [--plan] [--list] [--evidence] [--no-cache] [--build]
                                 [--allow-stale] [--no-retry] [--keep]

Goal: the least test time for the coverage a change needs.

* **What runs.** ``scripts/test_manifest.json`` registers every suite (one
  runner) and its groups (one invocation). Tiers are cumulative — t0 static
  and process checks; t1 adds the unit groups of the affected suites; t2
  adds their integration / GUI groups (the work-item gate); t3 runs every
  suite and group. perf, stress, soak, live and package are explicit lanes.
* **Affected.** The changed paths (the request's registered paths with
  ``--request``, else ``git diff HEAD`` plus new files, or ``--base`` /
  ``--paths``) select suites through ``scripts/test_selection.py`` (qmake
  graph + manifest inputs). A changed path nothing claims selects everything.
* **Never twice.** A group whose binary (GNU build id), executed binaries,
  inputs and arguments are identical to its last passing run is reported
  CACHED and not re-run (``<build>/test-results/cache.json``; ``--no-cache``).
* **In parallel, isolated.** Groups are split into shards
  (PROJECT_TEST_SHARD) and run concurrently (``--jobs``, longest first); each
  process gets private XDG data / config / cache / state / runtime / TMP
  directories under ``tmp/tr/<run>/<job>/`` (short:
  local socket paths are built from them), so
  no test writes the user's profile or another process's files.
  ``exclusive`` groups (perf, stress, soak, live) run alone afterwards.
* **Trustworthy.** A binary that is older than its sources is STALE and not
  run (``--build`` builds first, ``--allow-stale`` overrides and records it);
  a binary replaced during its run makes the result ENVIRONMENTAL; a case
  that failed under parallel load is re-run alone and reported FLAKY if it
  then passes; failures listed in ``scripts/test_quarantine.json`` (owner,
  reason, expiry) are EXPECTED / PRE-EXISTING, never hidden.
* **Recorded.** Every run writes ``<build>/test-results/runs/<run-id>.json``
  (revision, changed paths, tier, per-job status / time / cases and — with
  ``--request`` — the fingerprint of the request's code) which the
  completion gate checks against the work record's ``**Test-Run:**`` line.

Exit status: 0 pass (FLAKY / EXPECTED / CACHED included and listed), 1 a
failure (FAIL, TIMEOUT, CRASH) or a failed --build, 3 nothing failed but
something could not run (STALE, MISSING, BLOCKED, ENVIRONMENTAL), 4 EMPTY
(nothing executed and nothing cached: the run proves nothing), 130
INTERRUPTED (SIGINT / SIGTERM; running jobs are killed), 2 usage.

Results: a runner reports cases as ``"results": "json"`` (PROJECT_TEST_RESULTS
JSONL), ``"junit"`` (a JUnit XML report written to $PROJECT_TEST_JUNIT),
``"tap"`` (TAP on stdout), ``"lines"`` (``PASS|FAIL|SKIP|TIMEOUT <name>``
lines) or ``"exit"`` (the exit code only).
"""

