def checkout() -> Path:
    """The top of the git work tree (the project checkout when the system is
    installed as a project subdirectory; ROOT otherwise)."""
    import agent_process
    return Path(agent_process.checkout_root(ROOT))


def system_paths(paths) -> list[str]:
    """Repository paths spelled relative to ROOT, the form of the manifest's
    globs and of every ROOT-relative join here (``../src/a.c`` for a project
    file when the system is installed as ``<project>/<dir>/``; unchanged when
    the system is the checkout top)."""
    import agent_process
    return [agent_process.system_relative(ROOT, p) for p in paths]


def git(*args: str) -> str:
    """git in the checkout: paths in and out are repository paths."""
    return subprocess.run(["git", *args], cwd=checkout(), capture_output=True, text=True, check=False).stdout


def changed_paths(args) -> tuple[list[str], str]:
    if args.paths:
        return sorted(set(args.paths)), "paths"
    if args.request:
        try:
            owned = request_owned_paths(Path(args.request))
        except NoClaim as error:
            raise SystemExit(str(error))
        return sorted(system_paths(owned)), f"request {Path(args.request).name}"
    if args.base:
        out = git("diff", "--name-only", f"{args.base}...HEAD") + git("diff", "--name-only", "HEAD")
        out += git("ls-files", "--others", "--exclude-standard")
        return sorted(set(system_paths(l for l in out.splitlines() if l))), f"since {args.base}"
    out = git("diff", "--name-only", "HEAD") + git("ls-files", "--others", "--exclude-standard")
    return sorted(set(system_paths(l for l in out.splitlines() if l))), "working tree vs HEAD"


class NoClaim(RuntimeError):
    """The request has no claim (never claimed, or already released)."""


def _claim_for(request_file: Path, root: Path = ROOT) -> dict:
    import agent_process
    data = agent_process.read_claim(agent_process.lock_path(root, Path(request_file).name))
    if not data:
        raise NoClaim(f"no claim for {Path(request_file).name} (scripts/claim.py --show)")
    return data


def qt5_makefiles(build_dir: Path, max_depth: int = 3) -> list[str]:
    """Every Makefile in the shadow tree (top level and up to ``max_depth``
    directories below it, nested SUBDIRS included) whose header says Qt 5
    qmake generated it, relative to the tree and sorted."""
    found = []
    for depth in range(max_depth + 1):
        for p in build_dir.glob("/".join(["*"] * depth + ["Makefile"])):
            try:
                head = p.read_text(encoding="utf-8", errors="replace")[:400]
            except OSError:
                continue
            if re.search(r"Generated by qmake \([^)]*\) \(Qt 5\.", head):
                found.append(str(p.relative_to(build_dir)))
    return sorted(found)


def request_owned_paths(request_file: Path, root: Path = ROOT) -> list[str]:
    return sorted((_claim_for(request_file, root).get("files") or {}).keys())


def request_fingerprint(request_file: Path, root: Path = ROOT) -> tuple[str, list[str]]:
    """sha256 over the content of the request's registered code paths
    (documentation and process records excluded): proves which code a test
    run exercised. One implementation, shared with the completion gate and
    the request commit (agent_process.request_fingerprint, REQ-DEVOPS-046).
    (fingerprint, paths)."""
    import agent_process
    return agent_process.request_fingerprint(root, _claim_for(request_file, root))


# ---------------------------------------------------------------- identity / cache
_BUILD_IDS: dict[str, str] = {}


def binary_identity(path: Path) -> str:
    key = str(path)
    if key in _BUILD_IDS:
        return _BUILD_IDS[key]
    identity = ""
    try:
        out = subprocess.run(["readelf", "-n", str(path)], capture_output=True, text=True,
                             check=False, timeout=60).stdout
        match = re.search(r"Build ID:\s*([0-9a-f]+)", out)
        if match:
            identity = "buildid:" + match.group(1)
    except (OSError, subprocess.TimeoutExpired):
        pass
    if not identity:
        digest = hashlib.sha256()
        with open(path, "rb") as handle:
            for chunk in iter(lambda: handle.read(1 << 20), b""):
                digest.update(chunk)
        identity = "sha256:" + digest.hexdigest()
    _BUILD_IDS[key] = identity
    return identity


def stat_identity(path: Path) -> tuple:
    try:
        st = path.stat()
        return (st.st_ino, st.st_size, st.st_mtime_ns)
    except OSError:
        return ()


def inputs_fingerprint(patterns: list[str], tracked: list[str]) -> str:
    digest = hashlib.sha256()
    for rel in tracked:
        if selection.matches(rel, patterns):
            try:
                st = (ROOT / rel).stat()
                digest.update(f"{rel}:{st.st_size}:{st.st_mtime_ns}\n".encode())
            except OSError:
                digest.update(f"{rel}:missing\n".encode())
    return digest.hexdigest()


class ResultCache:
    def __init__(self, path: Path) -> None:
        self.path = path
        self.lock = threading.Lock()
        try:
            self.data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            self.data = {}

    def get(self, key: str) -> dict | None:
        return self.data.get(key)

    def put(self, key: str, value: dict) -> None:
        with self.lock:
            self.data[key] = value

    def save(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        # Merge with what another run saved meanwhile, then replace atomically.
        try:
            current = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            current = {}
        current.update(self.data)
        tmp = self.path.with_suffix(f".{os.getpid()}.tmp")
        tmp.write_text(json.dumps(current, indent=1, sort_keys=True), encoding="utf-8")
        os.replace(tmp, self.path)


