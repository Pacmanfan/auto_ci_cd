# ---------------------------------------------------------------- manifest
def load_manifest(path: Path = MANIFEST, root: Path = ROOT) -> dict:
    manifest = json.loads(path.read_text(encoding="utf-8"))
    live = manifest.get("live_scripts")
    if live:
        detect = live.get("requires_detect") or {}
        for script in sorted(root.glob(live["glob"])):
            text = script.read_text(encoding="utf-8", errors="replace")
            requires = [name for name, pattern in detect.items() if re.search(pattern, text)]
            rel = script.relative_to(root).as_posix()
            manifest["suites"].append({
                "id": f"live:{script.stem}", "kind": "command", "results": "exit",
                "command": ["python3", rel], "uses": live.get("uses", []), "requires": requires,
                "inputs": [rel],
                "groups": {"run": {"tiers": live["tiers"], "exclusive": True,
                                   "expected_seconds": live.get("expected_seconds", 120)}}})
    return manifest


def tier_set(manifest: dict, tier: str) -> set[str]:
    tiers = manifest["tiers"]
    if tier not in tiers:
        raise SystemExit(f"unknown tier {tier!r} (known: {', '.join(tiers)})")
    return {tier, *tiers[tier].get("includes", [])}


