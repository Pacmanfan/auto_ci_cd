def load_durations(build_dir: Path) -> dict:
    try:
        return json.loads((build_dir / "test-results" / "durations.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def save_durations(build_dir: Path, jobs: list["Job"]) -> None:
    """Per-case wall seconds of the cases that completed, for the next run's
    shard balancing (merged with what other runs recorded)."""
    path = build_dir / "test-results" / "durations.json"
    data = load_durations(build_dir)
    for job in jobs:
        for case in job.cases:
            if case.get("status") in ("PASS", "FAIL", "SKIP") and "seconds" in case:
                data.setdefault(job.suite["id"], {})[case["name"]] = round(float(case["seconds"]), 3)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(f".{os.getpid()}.tmp")
    tmp.write_text(json.dumps(data, indent=0, sort_keys=True), encoding="utf-8")
    os.replace(tmp, path)


_LISTING_SUPPORT: dict[str, bool] = {}


def supports_case_lists(binary: Path, declared: bool | None = None) -> bool:
    """Built with PROJECT_TEST_LIST / PROJECT_TEST_CASES (the project's test framework)?
    A binary from before would ignore the variables and run its whole suite.
    A suite may declare it (``"supports_case_list": true|false``); otherwise
    the binary is scanned for the variable name."""
    if declared is not None:
        return bool(declared)
    key = binary_identity(binary)
    if key not in _LISTING_SUPPORT:
        found = False
        needle = b"PROJECT_TEST_CASES"
        tail = b""
        with open(binary, "rb") as handle:
            for chunk in iter(lambda: handle.read(1 << 22), b""):
                if needle in tail + chunk:
                    found = True
                    break
                tail = chunk[-len(needle):]
        _LISTING_SUPPORT[key] = found
    return _LISTING_SUPPORT[key]


def list_cases(command: list[str], env: dict, cwd: Path) -> list[str]:
    run_env = dict(env, PROJECT_TEST_LIST="1")
    for name in ("PROJECT_TEST_SHARD", "PROJECT_TEST_CASES", "PROJECT_TEST_RESULTS"):
        run_env.pop(name, None)
    try:
        out = subprocess.run(command, cwd=cwd, env=run_env, capture_output=True, text=True, timeout=120).stdout
    except (OSError, subprocess.TimeoutExpired):
        return []
    return [line[5:].strip() for line in out.splitlines() if line.startswith("CASE ")]


def default_case_seconds(cases: list[str], known: dict, expected: float) -> float:
    """What an unrecorded case is assumed to take: the median of the recorded
    ones when enough are recorded, else the group's expected time per case."""
    values = sorted(known[c] for c in cases if c in known)
    if values and len(values) >= max(3, len(cases) // 4):
        return values[len(values) // 2]
    return expected / max(1, len(cases))


def balance(cases: list[str], known: dict, shards: int, default: float = 1.0) -> list[list[str]]:
    """Longest-processing-time-first: each case (longest recorded first; an
    unknown case counts as `default`) goes to the shard with the least work."""
    weighted = sorted(cases, key=lambda c: -known.get(c, default))
    bins: list[list] = [[0.0, []] for _ in range(shards)]
    for case in weighted:
        target = min(bins, key=lambda b: b[0])
        target[0] += known.get(case, default)
        target[1].append(case)
    return [b[1] for b in bins if b[1]]


def requirement_problem(requires: list[str]) -> str | None:
    for requirement in requires or []:
        kind, _, value = requirement.partition(":")
        if kind == "file" and not (ROOT / value).exists():
            return f"missing {value}"
        if kind == "exe" and shutil.which(value) is None:
            return f"no {value} on PATH"
        if kind == "python" and importlib.util.find_spec(value) is None:
            return f"python module {value} not installed"
        if kind == "env" and not os.environ.get(value):
            return f"${value} not set"
        # Named resources opted into through the environment
        # (tests.requirement_env: testdata -> $PROJECT_TEST_DATA, hardware -> $PROJECT_LIVE_HW_ARGS).
        variable = CFG["tests"]["requirement_env"].get(requirement)
        if variable:
            value = os.environ.get(variable, "")
            if not value:
                return f"needs {requirement} (set ${variable} to opt in)"
            if requirement == "testdata" and not Path(value).is_dir():
                return f"${variable} is not a directory"
    return None


_BUILD_TREES: dict[Path, tuple[dict[str, float], set[str]]] = {}


def build_tree_inputs(build_dir: Path) -> tuple[dict[str, float], set[str]]:
    """What the qmake Makefiles of build_dir say the build reads: for every
    .pro / .pri a Makefile is generated from (its "Makefile:" rule), the
    newest mtime of those Makefiles; and every source, header, form or proto
    any Makefile mentions (qmake writes each object's header dependencies).
    Paths are normalised absolute strings. Empty without qmake Makefiles."""
    key = build_dir.resolve()
    if key not in _BUILD_TREES:
        regenerated: dict[str, float] = {}
        mentioned: set[str] = set()
        for makefile in key.glob("**/Makefile"):
            try:
                generated = makefile.stat().st_mtime
                text = makefile.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            here = str(makefile.parent)
            tokens = {t.rstrip("\\") for t in text.split() if os.path.splitext(t.rstrip("\\"))[1] in SOURCE_SUFFIXES}
            mentioned.update(os.path.normpath(os.path.join(here, t)) for t in tokens)
            rule = text.find("\nMakefile: ")
            if rule < 0:
                continue
            deps = []
            for line in text[rule + 11:].splitlines():
                deps += line.rstrip().rstrip("\\").split()
                if not line.rstrip().endswith("\\"):
                    break
            for dep in deps:
                if dep.endswith((".pro", ".pri")):
                    path = os.path.normpath(os.path.join(here, dep))
                    regenerated[path] = max(regenerated.get(path, 0.0), generated)
        _BUILD_TREES[key] = (regenerated, mentioned)
    return _BUILD_TREES[key]


def sources_newer(binary: Path, patterns: list[str], tracked: list[str]) -> str | None:
    """A tracked file matching the suite's ``sources`` globs that changed after
    ``binary`` was built (build-system independent staleness), or None."""
    try:
        built = binary.stat().st_mtime
    except OSError:
        return None
    newest, newest_file = 0.0, ""
    for rel in tracked:
        if selection.matches(rel, patterns):
            try:
                mtime = (ROOT / rel).stat().st_mtime
            except OSError:
                continue
            if mtime > built + 1.0 and mtime > newest:
                newest, newest_file = mtime, rel
    return f"{newest_file} is newer than the binary" if newest_file else None


def stale_reason(graph: selection.ProjectGraph, binary: Path, projects: list[str],
                 build_dir: Path | None = None) -> str | None:
    """Why make would rebuild `binary` for the inputs of `projects`, or None.
    With qmake Makefiles (build_tree_inputs): a .pro / .pri counts when it
    changed after the Makefiles generated from it; any other input only when
    the build mentions it (a header nothing includes, in an include
    directory, cannot make a binary stale) and it is newer than the binary.
    Without them every input is compared with the binary."""
    try:
        built = binary.stat().st_mtime
    except OSError:
        return None
    regenerated, mentioned = build_tree_inputs(build_dir) if build_dir else ({}, set())
    qmake = bool(regenerated or mentioned)
    newest, newest_file = 0.0, ""
    for pro in projects:
        if pro not in graph.projects:
            continue
        for rel in graph.project_files(pro):
            suffix = Path(rel).suffix
            if suffix not in SOURCE_SUFFIXES:
                continue
            try:
                mtime = (ROOT / rel).stat().st_mtime
            except OSError:
                continue
            path = os.path.normpath(ROOT / rel)
            if qmake and suffix in (".pro", ".pri"):
                reference = regenerated.get(path)
                if reference is None or mtime <= reference + 1.0:
                    continue
            elif (qmake and path not in mentioned) or mtime <= built + 1.0:
                continue
            if mtime > newest:
                newest, newest_file = mtime, rel
    if newest_file:
        return f"{newest_file} is newer than the binary" if Path(newest_file).suffix not in (".pro", ".pri") \
            else f"{newest_file} changed after qmake last generated the Makefiles (run make)"
    return None


_TEST_SUITES = re.compile(r"^\s*\*\*Test-Suites:\*\*\s*(.+)$", re.MULTILINE)


def requested_suites(args) -> list[tuple[str, str]]:
    """(suite id, reason) named by the **Test-Suites:** header of the work
    records linked to --request."""
    if not getattr(args, "request", None):
        return []
    import agent_process
    out = []
    for work in agent_process.linked_work_records(ROOT, Path(args.request).name):
        m = _TEST_SUITES.search(work.read_text(encoding="utf-8", errors="ignore"))
        if m:
            for suite_id in re.split(r"[,\s]+", m.group(1).strip()):
                if suite_id:
                    out.append((suite_id, f"requested by {work.name[:11]}"))
    return out


def plan(args, manifest: dict, build_dir: Path, cache: ResultCache) -> tuple[list[Job], dict]:
    tiers = tier_set(manifest, args.tier)
    lane = args.tier in LANES
    full_scope = args.all or args.tier == "t3" or lane
    tracked = system_paths(selection.tracked_files(checkout()))
    graph = selection.ProjectGraph(ROOT, tracked)
    changed, source = changed_paths(args)
    chosen, unmapped = selection.select_suites(graph, manifest["suites"], changed)
    # Suites a work record linked to the request names explicitly
    # (**Test-Suites:** a, b): selected whatever the changed paths say.
    for suite_id, reason in requested_suites(args):
        chosen.setdefault(suite_id, []).append(reason)
    if unmapped and not full_scope:
        full_scope = True
    info = {"changed": changed, "changes_from": source, "unmapped": unmapped,
            "affected_suites": chosen, "scope": "all" if full_scope else "affected"}
    durations = load_durations(build_dir)
    jobs: list[Job] = []
    for suite in manifest["suites"]:
        if args.suite and not any(fnmatch.fnmatchcase(suite["id"], pattern) for pattern in args.suite):
            continue
        groups = {name: g for name, g in suite["groups"].items() if set(g.get("tiers", [])) & tiers}
        for name, group in list(groups.items()):
            if group.get("superseded_by") in groups:
                del groups[name]
        if not groups:
            continue
        always = all(set(g.get("tiers", [])) <= {"t0"} for g in groups.values())
        if not (always or full_scope or args.suite or suite["id"] in chosen):
            continue
        reasons = chosen.get(suite["id"], ["t0 (always)" if always else
                                            ("--suite" if args.suite else f"{info['scope']} scope")])
        for name, group in groups.items():
            jobs += make_jobs(suite, name, group, build_dir, graph, tracked, cache, args, reasons, durations)
    return jobs, info


def make_jobs(suite, name, group, build_dir, graph, tracked, cache, args, reasons, durations=None) -> list[Job]:
    durations = durations or {}
    env = dict(os.environ)
    for overrides in (suite.get("env") or {}, group.get("env") or {}):
        for key, value in overrides.items():
            if value is None:
                env.pop(key, None)      # null removes an inherited setting
            else:
                env[key] = value
    for var, rel in (suite.get("env_from_build") or {}).items():
        env[var] = str(build_dir / rel)
    watch: list[Path] = []
    status, detail = "PENDING", ""
    if suite["kind"] == "binary":
        binary = build_dir / suite["binary"]
        command = [str(binary), *group.get("args", [])]
        watch.append(binary)
        for pro in suite.get("uses", []):
            used = build_dir / Path(pro).parent / Path(pro).stem
            if used.exists():
                watch.append(used)
        if not binary.exists():
            status, detail = "MISSING", f"{binary} not built (make -C {build_dir} or --build)"
        elif not args.allow_stale:
            # Each binary against the inputs of the project that builds it: the
            # suite's own binary, then every binary it executes.
            checks = ([(binary, suite["project"])] if suite.get("project") else []) + [
                (build_dir / Path(pro).parent / Path(pro).stem, pro) for pro in suite.get("uses", [])]
            for checked, pro in checks:
                why = stale_reason(graph, checked, [pro], build_dir) if checked.exists() else None
                if why:
                    status, detail = "STALE", f"{checked.name}: {why}; rebuild (--build) or --allow-stale"
                    break
            if status == "PENDING" and suite.get("sources"):
                # Any build system: a declared source newer than the binary.
                why = sources_newer(binary, suite["sources"], tracked)
                if why:
                    status, detail = "STALE", f"{binary.name}: {why}; rebuild (--build) or --allow-stale"
    else:
        command = list(group.get("command") or suite["command"])
        if command and command[0] == "python3":
            # The registry's portable spelling of "this Python": Windows has no
            # python3 executable on PATH (tools/audit_system/checks.py does the same).
            command[0] = sys.executable
    problem = requirement_problem(list(suite.get("requires", [])) + list(group.get("requires", [])))
    if problem and status == "PENDING":
        status, detail = "BLOCKED", problem
    cwd = ROOT / suite.get("cwd", ".")
    expected = float(group.get("expected_seconds", 60))
    shards = max(1, int(group.get("shards", 1))) if suite.get("results") == "json" else 1
    if args.max_shards:
        shards = min(shards, args.max_shards)
    cache_key = None
    cacheable = suite["kind"] == "binary" or suite.get("inputs")
    if cacheable and status == "PENDING" and not suite["id"].startswith("live:") and not group.get("exclusive"):
        material = {"v": RUNNER_VERSION, "suite": suite["id"], "group": name,
                    "command": [Path(c).name if i == 0 else c for i, c in enumerate(command)],
                    "binaries": [binary_identity(p) for p in watch if p.exists()],
                    "inputs": inputs_fingerprint(suite.get("inputs", []), tracked),
                    "select": [group.get("cases"), group.get("exclude_cases")],
                    "env": {k: v for k, v in sorted({**(suite.get("env") or {}), **(group.get("env") or {})}.items())}}
        if suite["kind"] != "binary":
            # A command suite is its scripts: fingerprint what it runs from.
            material["scripts"] = inputs_fingerprint(suite.get("inputs", []) + [c for c in command if "/" in c], tracked)
        cache_key = hashlib.sha256(json.dumps(material, sort_keys=True).encode()).hexdigest()
        if not args.no_cache:
            hit = cache.get(cache_key)
            if hit and hit.get("status") == "PASS":
                status, detail = "CACHED", f"unchanged since run {hit.get('run_id')} ({hit.get('at', '')[:19]})"
    subsets: list[list[str] | None] = [None] * shards
    weights = [expected / shards] * shards
    serial: list[str] = []
    selects = group.get("cases") or group.get("exclude_cases")
    if status == "PENDING" and selects and not supports_case_lists(watch[0], suite.get("supports_case_list")):
        status, detail = "BLOCKED", f"{watch[0].name} cannot run a case list (rebuild it)"
    if status == "PENDING" and suite["kind"] == "binary" and suite.get("results") == "json" \
            and (shards > 1 or suite.get("load_sensitive") or selects) and supports_case_lists(watch[0], suite.get("supports_case_list")):
        cases = list_cases(command, env, cwd)
        # A group can take part of a runner's cases ("cases") or leave some to
        # another group ("exclude_cases"), e.g. hardware cases to the live lane.
        if group.get("cases"):
            cases = [c for c in cases if any(fnmatch.fnmatchcase(c, p) for p in group["cases"])]
        cases = [c for c in cases if not any(fnmatch.fnmatchcase(c, p) for p in group.get("exclude_cases", []))]
        if not cases:
            status, detail = "NO_TESTS", "no case matches the group's case selection"
        # Known timing-sensitive cases run alone after the parallel phase
        # (they still run and must pass; only their scheduling changes).
        sensitive = set(suite.get("load_sensitive") or [])
        serial = [c for c in cases if c in sensitive]
        cases = [c for c in cases if c not in sensitive]
        if cases and shards == 1 and serial:
            subsets, weights = [cases], [expected]
        elif cases:
            known = durations.get(suite["id"], {})
            default = default_case_seconds(cases, known, expected)
            # Each shard's list in registration order: the order the runner
            # executes it, so a crash is attributed to the right case.
            order = {case: index for index, case in enumerate(cases)}
            subsets = [sorted(subset, key=order.__getitem__) for subset in balance(cases, known, shards, default)]
            weights = [sum(known.get(c, default) for c in subset) for subset in subsets]
        shards = len(subsets)
    timeout = float(group.get("timeout_seconds") or max(300.0, 4 * max(weights) + 120))
    jobs = []
    wrapper = group.get("wrapper") or []
    for shard in range(shards):
        # A group that needs a display runs under xvfb-run; each shard starts
        # its display search in its own range so parallel shards never race.
        wrapped = [w.replace("{display}", str(300 + 10 * shard)) for w in wrapper] + command
        jobs.append(Job(suite=suite, group_name=name, group=group, shard=shard, shards=shards,
                        command=wrapped, cwd=cwd, env=env, timeout=timeout,
                        exclusive=bool(group.get("exclusive")), watch=watch,
                        expected=weights[shard], cache_key=cache_key, status=status, detail=detail,
                        reasons=list(reasons), case_subset=subsets[shard]))
    if serial:
        known = durations.get(suite["id"], {})
        wrapped = [w.replace("{display}", str(300 + 10 * shards)) for w in wrapper] + command
        jobs.append(Job(suite=suite, group_name=name, group=group, shard=shards, shards=shards + 1,
                        command=wrapped, cwd=cwd, env=env, timeout=timeout, exclusive=True, watch=watch,
                        expected=sum(known.get(c, 30.0) for c in serial), cache_key=cache_key,
                        status=status, detail=detail, reasons=list(reasons) + ["load-sensitive cases, alone"],
                        case_subset=serial))
        for job in jobs:
            job.shards = shards + 1
    return jobs


# ---------------------------------------------------------------- execution
CASE_LINE = re.compile(r"^(PASS|FAIL|SKIP|TIMEOUT)\s+(\S+)")


def isolated_env(job: Job, workdir: Path) -> dict:
    env = dict(job.env)
    for name in ("data", "config", "cache", "state", "tmp"):
        (workdir / name).mkdir(parents=True, exist_ok=True)
    runtime = workdir / "runtime"
    runtime.mkdir(parents=True, exist_ok=True)
    os.chmod(runtime, 0o700)
    env.update(XDG_DATA_HOME=str(workdir / "data"), XDG_CONFIG_HOME=str(workdir / "config"),
               XDG_CACHE_HOME=str(workdir / "cache"), XDG_STATE_HOME=str(workdir / "state"),
               XDG_RUNTIME_DIR=str(runtime), TMPDIR=str(workdir / "tmp"))
    # Application data roots are not forced here: the project's runners
    # isolate them themselves (the source project's runners set their data
    # root to a temp tree when it was unset).
    for name in SCRUBBED_ENV:
        env.pop(name, None)
    env.pop("PROJECT_TEST_SHARD", None)
    env.pop("PROJECT_TEST_CASES", None)
    env.pop("PROJECT_TEST_LIST", None)
    if job.case_subset is not None:
        cases_file = workdir / "cases.txt"
        cases_file.write_text("\n".join(job.case_subset) + "\n", encoding="utf-8")
        env["PROJECT_TEST_CASES"] = str(cases_file)
    elif job.shards > 1:
        env["PROJECT_TEST_SHARD"] = f"{job.shard}/{job.shards}"
    if job.suite.get("results") == "json":
        env["PROJECT_TEST_RESULTS"] = str(workdir / "results.jsonl")
    if job.suite.get("results") == "junit":
        env["PROJECT_TEST_JUNIT"] = str(workdir / "junit.xml")
    return env


_RUNNING: set = set()          # live job processes, killed when the run is interrupted
_RUNNING_LOCK = threading.Lock()


def kill_running() -> None:
    with _RUNNING_LOCK:
        procs = list(_RUNNING)
    for proc in procs:
        plat.signal_group(proc.pid)


_JOB_COUNTER = [0]
_JOB_COUNTER_LOCK = threading.Lock()
# Local (Unix) sockets live under TMPDIR / XDG_RUNTIME_DIR and sun_path holds
# 107 bytes: per-job directories are numbered, not named after the job, and
# the run directory itself is short (scratch_root()).
SOCKET_PATH_BUDGET = 60


def scratch_root(run_id: str) -> Path:
    """Short per-run scratch under <paths.scratch>/tr/; the system temp directory
    only when the checkout path itself is too long for socket paths."""
    short = run_id.replace("T", "")[-10:]
    candidate = ROOT / CFG["paths"]["scratch"] / "tr" / short
    if len(str(candidate)) + 8 > SOCKET_PATH_BUDGET:
        import tempfile
        candidate = Path(tempfile.gettempdir()) / f"art-{short}"
    return candidate


def execute(job: Job, run_dir: Path, command: list[str] | None = None, tag: str = "") -> None:
    with _JOB_COUNTER_LOCK:
        _JOB_COUNTER[0] += 1
        number = _JOB_COUNTER[0]
    workdir = run_dir / f"{number:03d}"
    shutil.rmtree(workdir, ignore_errors=True)
    workdir.mkdir(parents=True)
    (workdir / "JOB").write_text(job.label + tag + "\n", encoding="utf-8")
    job.workdir, job.log = workdir, workdir / "output.log"
    env = isolated_env(job, workdir)
    before = [stat_identity(p) for p in job.watch]
    started = time.monotonic()
    with open(job.log, "wb") as log:
        proc = subprocess.Popen(command or job.command, cwd=job.cwd, env=env, stdout=log,
                                stderr=subprocess.STDOUT, **plat.group_popen_kwargs())
        with _RUNNING_LOCK:
            _RUNNING.add(proc)
        try:
            job.rc = proc.wait(timeout=job.timeout)
        except subprocess.TimeoutExpired:
            for hard in (False, True):
                if not plat.signal_group(proc.pid, hard=hard):
                    break
                try:
                    proc.wait(timeout=10)
                    break
                except subprocess.TimeoutExpired:
                    continue
            job.rc = None
        finally:
            with _RUNNING_LOCK:
                _RUNNING.discard(proc)
    job.seconds = time.monotonic() - started
    job.cases = parse_cases(job, workdir)
    after = [stat_identity(p) for p in job.watch]
    if before != after:
        job.status, job.detail = "ENVIRONMENTAL", "a binary under test was replaced during the run (shared build tree)"
        return
    failed = [c for c in job.cases if c["status"] in ("FAIL", "TIMEOUT")]
    if job.rc is None:
        job.status, job.detail = "TIMEOUT", f"no result within {job.timeout:.0f}s (process group killed)"
    elif job.rc == 124 or any(c["status"] == "TIMEOUT" for c in job.cases):
        job.status = "TIMEOUT"
        job.detail = "watchdog: " + ", ".join(c["name"] for c in job.cases if c["status"] == "TIMEOUT")
    elif crashed(job.rc):
        job.status, job.detail = "CRASH", f"killed by signal {-job.rc if job.rc < 0 else job.rc - 128}"
    elif job.rc == 2 and not job.cases and job.suite["kind"] == "binary":
        job.status, job.detail = "NO_TESTS", "no case selected"
    elif job.rc == 0 and not failed:
        job.status = "PASS"
    else:
        job.status = "FAIL"
        job.detail = (", ".join(c["name"] for c in failed[:5]) + (" ..." if len(failed) > 5 else "")
                      if failed else f"exit {job.rc}")


def crashed(rc: int | None) -> bool:
    """Killed by a signal: negative for the runner itself, 128 + signal when
    a wrapper (xvfb-run, a shell) reports it."""
    return rc is not None and (rc < 0 or 128 < rc <= 128 + 64)


MAX_CONTINUATIONS = 5


def continue_after_abort(job: Job, run_dir: Path) -> None:
    """A crash or a hang ends the process, not the shard. The case it ended
    in is the first selected case without a result (case lists are in
    registration order, the order the runners execute them) unless the
    runner's watchdog recorded it already; it is recorded as CRASH / TIMEOUT
    and the cases after it run in a continuation process, so one bad case
    never silently drops the rest of its shard."""
    if job.status not in ("CRASH", "TIMEOUT") or job.suite.get("results") != "json" or not job.case_subset:
        return
    events, detail = [], job.detail
    part_status, part_cases = job.status, list(job.cases)
    for attempt in range(MAX_CONTINUATIONS + 1):
        recorded = {c["name"] for c in job.cases}
        remaining = [c for c in job.case_subset if c not in recorded]
        if remaining and not any(c["status"] == "TIMEOUT" for c in part_cases):
            job.cases.append({"name": remaining[0], "status": part_status})
            events.append(f"{detail} in {remaining.pop(0)}")
        else:
            events.append(detail)
        if not remaining or attempt == MAX_CONTINUATIONS:
            break
        part = Job(**{**job.__dict__, "cases": [], "flaky": [], "expected_failures": [], "status": "PENDING",
                      "detail": "", "case_subset": remaining})
        execute(part, run_dir, tag=f"-continued-{attempt + 1}")
        job.cases.extend(part.cases)
        job.seconds += part.seconds
        if part.status not in ("CRASH", "TIMEOUT"):
            if part.status == "ENVIRONMENTAL":
                events.append(f"continuation ENVIRONMENTAL: {part.detail}")
            break
        part_status, part_cases, detail = part.status, part.cases, part.detail
    recorded = {c["name"] for c in job.cases}
    not_run = [c for c in job.case_subset if c not in recorded]
    job.detail = "; ".join(events) + (f"; {len(not_run)} case(s) not run" if not_run else "")


def parse_junit(path: Path) -> list[dict]:
    """Cases of a JUnit XML report (testsuite/testcase; failure, error,
    skipped children), as the orchestrator's case rows."""
    import xml.etree.ElementTree as ET
    try:
        tree = ET.parse(str(path))
    except (ET.ParseError, OSError):
        return []
    cases = []
    for case in tree.getroot().iter("testcase"):
        name = case.get("name", "?")
        group = case.get("classname", "")
        status = "PASS"
        if case.find("failure") is not None or case.find("error") is not None:
            status = "FAIL"
        elif case.find("skipped") is not None:
            status = "SKIP"
        row = {"name": f"{group}/{name}".lstrip("/"), "status": status}
        with contextlib.suppress(TypeError, ValueError):
            row["seconds"] = float(case.get("time"))
        cases.append(row)
    return cases


_TAP_LINE = re.compile(r"^(not ok|ok)\b\s*(\d+)?\s*-?\s*([^#]*)(#\s*(SKIP|TODO)\b.*)?", re.IGNORECASE)


def parse_tap(text: str) -> list[dict]:
    """Cases of TAP output ("ok 1 - name", "not ok 2 - name", "# SKIP")."""
    cases = []
    for line in text.splitlines():
        m = _TAP_LINE.match(line.strip())
        if not m:
            continue
        name = m.group(3).strip() or f"test {m.group(2)}"
        if m.group(5):
            status = "SKIP"
        else:
            status = "FAIL" if m.group(1).lower() == "not ok" else "PASS"
        cases.append({"name": name, "status": status})
    return cases


def parse_cases(job: Job, workdir: Path) -> list[dict]:
    cases: list[dict] = []
    kind = job.suite.get("results")
    if kind == "junit":
        report = workdir / "junit.xml"
        return parse_junit(report) if report.exists() else []
    if kind == "tap":
        return parse_tap(job.log.read_text(encoding="utf-8", errors="replace")) if job.log and job.log.exists() else []
    results = workdir / "results.jsonl"
    if results.exists():
        for line in results.read_text(encoding="utf-8", errors="replace").splitlines():
            try:
                row = json.loads(line)
            except ValueError:
                continue
            if row.get("summary"):
                continue
            row["name"] = f"{row.get('group', '')}/{row.get('name', '')}".lstrip("/")
            cases.append(row)
        return cases
    if job.log and job.log.exists():
        for line in job.log.read_text(encoding="utf-8", errors="replace").splitlines():
            match = CASE_LINE.match(line)
            if match:
                cases.append({"name": match.group(2), "status": match.group(1)})
    return cases


def retry_isolated(job: Job, run_dir: Path) -> None:
    """Re-run each failed case of a job that ran under parallel load, alone.
    A case that passes alone is FLAKY (reported, not cached). A crash is
    never downgraded: passing alone only shows it is intermittent."""
    failed = [c for c in job.cases if c["status"] in ("FAIL", "TIMEOUT", "CRASH")]
    if job.status not in FAILING or job.suite["kind"] != "binary":
        return
    solo = Job(**{**job.__dict__, "shards": 1, "shard": 0, "cases": [], "flaky": [],
                  "expected_failures": [], "status": "PENDING", "case_subset": None})
    if job.suite.get("results") == "json" and failed and len(failed) <= 10:
        still = []
        for case in failed:
            name = case["name"]
            # How the runner's --filter spells a case: the recorded name
            # ("group/name", default) or the name without its group
            # ("filter_format": "name").
            text = name.split("/", 1)[-1] if job.suite.get("filter_format") == "name" else name
            execute(solo, run_dir, [*job.command, "--filter", text], tag=f"-retry-{len(still)}-{abs(hash(name)) % 10000}")
            if solo.status == "PASS" and case["status"] != "CRASH":
                job.flaky.append(name)
            elif solo.status == "PASS":
                job.detail += f"; {name} passed alone (intermittent crash)"
            else:
                still.append(name)
        if not still and job.status != "CRASH":
            job.status, job.detail = "FLAKY", "passed alone: " + ", ".join(job.flaky)
    elif job.suite.get("results") != "json" and job.expected <= 120:
        execute(solo, run_dir, tag="-retry")
        if solo.status == "PASS" and job.status == "CRASH":
            job.detail += "; passed when re-run alone (intermittent crash)"
        elif solo.status == "PASS":
            job.flaky = [c["name"] for c in failed] or [job.label]
            job.status, job.detail = "FLAKY", "passed when re-run alone"


def load_quarantine(path: Path = QUARANTINE) -> list[dict]:
    try:
        return json.loads(path.read_text(encoding="utf-8")).get("entries", [])
    except (OSError, ValueError):
        return []


def apply_quarantine(job: Job, entries: list[dict], today: str, warnings: list[str]) -> None:
    """Quarantined FAIL cases are EXPECTED / PRE-EXISTING, also inside a job
    that crashed or hung (the crash or hang itself is never quarantined). A
    job whose remaining failures are all quarantined or FLAKY is EXPECTED."""
    if job.status not in FAILING:
        return
    failed = [c["name"] for c in job.cases if c["status"] == "FAIL" and c["name"] not in job.flaky]
    if not failed:
        return
    for name in failed:
        for entry in entries:
            if entry.get("suite") == job.suite["id"] and fnmatch.fnmatchcase(name, entry.get("case", "")):
                if entry.get("expires", "9999-12-31") < today:
                    warnings.append(f"quarantine entry for {job.suite['id']}:{entry.get('case')} expired "
                                    f"{entry.get('expires')} ({entry.get('owner')}): the failure counts")
                    continue
                job.expected_failures.append(name)
                break
    if job.status == "FAIL" and set(failed) == set(job.expected_failures):
        job.status = "EXPECTED"
        job.detail = "EXPECTED / PRE-EXISTING (scripts/test_quarantine.json): " + ", ".join(failed) \
            + ("; passed alone: " + ", ".join(job.flaky) if job.flaky else "")


def run_pool(jobs: list[Job], workers: int, run_dir: Path, verbose: bool) -> None:
    pending = sorted((j for j in jobs if j.status == "PENDING" and not j.exclusive),
                     key=lambda j: -j.expected)
    exclusive = [j for j in jobs if j.status == "PENDING" and j.exclusive]
    lock = threading.Lock()
    done = [0]
    total = len(pending) + len(exclusive)

    def report(job: Job) -> None:
        with lock:
            done[0] += 1
            cases = len(job.cases)
            print(f"[run_tests] {done[0]:3d}/{total} {job.status:8s} {job.label:44s} {job.seconds:7.1f}s"
                  f"  {cases} case(s){'  ' + job.detail if job.detail and job.status != 'PASS' else ''}",
                  flush=True)

    def worker() -> None:
        while True:
            with lock:
                if not pending:
                    return
                job = pending.pop(0)
            execute(job, run_dir)
            continue_after_abort(job, run_dir)
            report(job)

    threads = [threading.Thread(target=worker, daemon=True) for _ in range(max(1, workers))]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    for job in exclusive:
        execute(job, run_dir)
        continue_after_abort(job, run_dir)
        report(job)


# ---------------------------------------------------------------- reporting
def classify(jobs: list[Job]) -> str:
    """FAIL > BLOCKED > EMPTY > PASS (FLAKY) > PASS (EXPECTED) > PASS.

    EMPTY: nothing was executed and nothing was a cached pass — no job, or
    only NO_TESTS / never-started jobs. It is never PASS ("never claim a test
    passed unless it ran"; CI_CD_ROADMAP COR-03)."""
    statuses = {j.status for j in jobs}
    if statuses & set(FAILING):
        return "FAIL"
    if statuses & set(NOT_RUN) - {"NO_TESTS"}:
        return "BLOCKED"
    if not statuses & set(EXECUTED):
        return "EMPTY"
    if "FLAKY" in statuses:
        return "PASS (FLAKY cases listed)"
    if "EXPECTED" in statuses:
        return "PASS (EXPECTED / PRE-EXISTING failures listed)"
    return "PASS"


def summarise(jobs: list[Job]) -> list[dict]:
    groups: dict[tuple, dict] = {}
    for job in jobs:
        key = (job.suite["id"], job.group_name)
        entry = groups.setdefault(key, {"suite": job.suite["id"], "group": job.group_name, "shards": job.shards,
                                        "statuses": [], "seconds": 0.0, "wall": 0.0, "cases": 0, "failed": [],
                                        "flaky": [], "expected": [], "detail": [], "reasons": job.reasons,
                                        "command": " ".join(Path(c).name if i == 0 and "/" in c else c
                                                            for i, c in enumerate(job.command))})
        entry["statuses"].append(job.status)
        entry["seconds"] += job.seconds
        entry["wall"] = max(entry["wall"], job.seconds)
        entry["cases"] += len(job.cases)
        entry["failed"] += [c["name"] for c in job.cases if c["status"] in ("FAIL", "TIMEOUT", "CRASH")
                            and c["name"] not in job.flaky and c["name"] not in job.expected_failures]
        entry["flaky"] += job.flaky
        entry["expected"] += job.expected_failures
        if job.detail and job.status not in ("PASS",):
            entry["detail"].append(job.detail)
    for entry in groups.values():
        order = ["FAIL", "TIMEOUT", "CRASH", "ENVIRONMENTAL", "STALE", "MISSING", "BLOCKED", "FLAKY",
                 "EXPECTED", "NO_TESTS", "PASS", "CACHED", "PENDING"]
        entry["status"] = min(entry["statuses"], key=order.index)
        entry["detail"] = sorted(set(entry["detail"]))
    return list(groups.values())


def print_summary(rows: list[dict], wall: float, classification: str, info: dict) -> None:
    print("\n| Suite / group | Status | Shards | Wall s | CPU s | Cases | Notes |")
    print("|---|---|---:|---:|---:|---:|---|")
    for row in rows:
        notes = "; ".join(row["detail"])[:160]
        print(f"| {row['suite']}/{row['group']} | {row['status']} | {row['shards']} | {row['wall']:.1f} | "
              f"{row['seconds']:.1f} | {row['cases']} | {notes} |")
    print(f"\nclassification: {classification}   wall: {wall:.1f}s   scope: {info['scope']} "
          f"({len(info['changed'])} changed path(s), {info['changes_from']})")
    if info["unmapped"]:
        print(f"unmapped changed paths (selected everything): {', '.join(info['unmapped'][:8])}"
              + (" ..." if len(info["unmapped"]) > 8 else ""))


def provenance() -> dict:
    """What a reader needs to reproduce the run (CI_CD_ROADMAP BLD-03)."""
    status = git("status", "--porcelain=v1", "--untracked-files=no")
    diff = subprocess.run(["git", "diff", "HEAD"], cwd=ROOT, capture_output=True).stdout
    return {
        "dirty": bool(status.strip()),
        "dirty_paths": len(status.splitlines()),
        "diff_sha256": hashlib.sha256(diff).hexdigest() if diff else None,
        "python": platform.python_version(),
        "platform": platform.platform(),
        "git": git("--version").strip(),
        "manifest_sha256": hashlib.sha256(MANIFEST.read_bytes()).hexdigest() if MANIFEST.exists() else None,
        "config_sha256": (hashlib.sha256((ROOT / cfgmod.CONFIG_FILE).read_bytes()).hexdigest()
                          if (ROOT / cfgmod.CONFIG_FILE).exists() else None),
        "build_system": CFG["build"]["system"],
    }


def write_record(build_dir: Path, run_id: str, args, info: dict, rows: list[dict], jobs: list[Job],
                 classification: str, wall: float, fingerprint: tuple[str, list[str]] | None,
                 warnings: list[str]) -> Path:
    runs = build_dir / "test-results" / "runs"
    runs.mkdir(parents=True, exist_ok=True)
    # The log of a job that did not pass is kept beside the record: the run's
    # scratch may live in the system temp directory and be cleaned there.
    kept = {}
    for j in jobs:
        if j.log and j.status not in ("PASS", "CACHED", "PENDING") and Path(j.log).is_file():
            dst = runs / run_id / f"{Path(j.workdir).name}-{re.sub(r'[^A-Za-z0-9_.-]', '_', j.label)}.log"
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(j.log, dst)
            kept[id(j)] = dst
    record = {
        "run_id": run_id, "runner_version": RUNNER_VERSION,
        "started_at": datetime.now(timezone.utc).isoformat(), "wall_seconds": round(wall, 1),
        "tier": args.tier, "scope": info["scope"], "changes_from": info["changes_from"],
        "changed": info["changed"], "unmapped": info["unmapped"],
        "head": git("rev-parse", "HEAD").strip(), "describe": git("describe", "--always", "--tags").strip(),
        "provenance": provenance(),
        "build_dir": str(build_dir), "jobs": args.jobs, "host": plat.hostname(),
        "request": Path(args.request).name if args.request else None,
        "request_fingerprint": fingerprint[0] if fingerprint else None,
        "request_code_paths": fingerprint[1] if fingerprint else [],
        "allow_stale": bool(args.allow_stale), "classification": classification,
        "warnings": warnings, "groups": rows,
        # Every case by name ("STATUS seconds name"): the scratch of passing
        # jobs is removed, and evidence must be able to show a case ran.
        "jobs_detail": [{"label": j.label, "status": j.status, "seconds": round(j.seconds, 2), "rc": j.rc,
                         "detail": j.detail, "log": str(kept.get(id(j)) or j.log) if j.log else None,
                         "cases": [f"{c['status']} {float(c.get('seconds') or 0):.3f} {c['name']}" for c in j.cases]}
                        for j in jobs],
    }
    path = runs / f"{run_id}.json"
    path.write_text(json.dumps(record, indent=1), encoding="utf-8")
    (build_dir / "test-results" / "latest.json").write_text(json.dumps(record, indent=1), encoding="utf-8")
    return path


def find_run_record(run_id: str, root: Path = ROOT) -> Path | None:
    """The run record of run_id: in a build tree of the checkout, else the
    copy its evidence keeps (evidence/<VER>/run-<id>.json) — build trees are
    local and disposable, evidence is committed."""
    cfg = cfgmod.load(root)
    trees = [cfg["paths"]["build_dir"], cfg["build"].get("build_dir") or ""]
    patterns = [f"{d}/test-results/runs/{run_id}.json" for d in dict.fromkeys(trees) if d and not Path(d).is_absolute()]
    patterns += [f"build/*/test-results/runs/{run_id}.json",
                 f"{cfgmod.LAYOUT['evidence']}/*/run-{run_id}.json"]
    for pattern in patterns:
        for candidate in sorted(root.glob(pattern)):
            return candidate
    for d in trees:
        if d and Path(d).is_absolute() and (Path(d) / "test-results" / "runs" / f"{run_id}.json").is_file():
            return Path(d) / "test-results" / "runs" / f"{run_id}.json"
    return None


RUN_ID = re.compile(r"\b\d{8}T\d{6}-\d+\b")


def evidence_markdown(record_path: Path, rows: list[dict], classification: str, wall: float, info: dict,
                      args, fingerprint) -> str:
    lines = [f"**Test-Run:** {record_path.stem} (`{record_path.relative_to(ROOT) if record_path.is_relative_to(ROOT) else record_path}`)",
             "",
             f"`python3 scripts/run_tests.py --tier {args.tier}"
             + (f" --request {Path(args.request).name}" if args.request else "")
             + (" --all" if args.all else "") + f" --build-dir {args.build_dir}` — {classification}, "
             f"{wall:.0f} s wall, scope {info['scope']}"
             + (f", request fingerprint `{fingerprint[0][:16]}`" if fingerprint else ""),
             "", "| Suite / group | Status | Wall s | Cases | Notes |", "|---|---|---:|---:|---|"]
    for row in rows:
        lines.append(f"| {row['suite']}/{row['group']} | {row['status']} | {row['wall']:.1f} | {row['cases']} | "
                     f"{'; '.join(row['detail'])[:200]} |")
    return "\n".join(lines)


# ---------------------------------------------------------------- main
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tier", default="t2")
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--request", help="request file: its registered paths are the change")
    scope.add_argument("--base", help="git ref: changes since it")
    scope.add_argument("--paths", nargs="+", help="explicit changed paths")
    parser.add_argument("--all", action="store_true", help="every suite of the tier, affected or not")
    parser.add_argument("--suite", action="append", help="only these suites (glob, repeatable)")
    parser.add_argument("--build-dir", default=str(DEFAULT_BUILD_DIR.relative_to(ROOT)
                                                    if DEFAULT_BUILD_DIR.is_relative_to(ROOT) else DEFAULT_BUILD_DIR))
    parser.add_argument("--jobs", type=int, default=max(2, min(8, (os.cpu_count() or 4) // 2)))
    parser.add_argument("--max-shards", type=int, default=0, help="cap shards per group (0: manifest)")
    parser.add_argument("--plan", action="store_true", help="print the plan and exit")
    parser.add_argument("--list", action="store_true", help="list suites, groups and tiers")
    parser.add_argument("--evidence", action="store_true", help="print a VER evidence block")
    parser.add_argument("--no-cache", action="store_true")
    parser.add_argument("--build", action="store_true", help="build first through the configured build "
                        "adapter (scripts/devsys_build.py; build.system in devsys.json)")
    parser.add_argument("--allow-stale", action="store_true")
    parser.add_argument("--no-retry", action="store_true")
    parser.add_argument("--keep", action="store_true", help="keep per-job scratch of passing jobs")
    args = parser.parse_args(argv)

    manifest = load_manifest()
    if args.list:
        for suite in manifest["suites"]:
            for name, group in suite["groups"].items():
                print(f"{suite['id'] + '/' + name:45s} tiers={','.join(group.get('tiers', []))}"
                      f" shards={group.get('shards', 1)} ~{group.get('expected_seconds', '?')}s")
        return 0
    build_dir = (ROOT / args.build_dir).resolve() if not Path(args.build_dir).is_absolute() else Path(args.build_dir)
    warnings: list[str] = []
    mixed = qt5_makefiles(build_dir) if REJECT_QT5_MAKEFILES else []
    if mixed:
        # Every one is named: a truncated list once hid one (VER-000317, ADR-000197).
        warnings.append(f"{build_dir.name}: {len(mixed)} Makefile(s) generated by Qt 5 qmake ({', '.join(mixed)}); "
                        f"the project supports Qt 6 only: regenerate with qmake6, never plain qmake")
    if args.build:
        import devsys_build
        rel_build = os.path.relpath(build_dir, ROOT)
        print(f"[run_tests] build ({CFG['build']['system']}) in {rel_build}", flush=True)
        built = devsys_build.run(ROOT, "build", rel_build)
        if built["status"] == "NOT_CONFIGURED":
            warnings.append("--build: build.system is 'none' in devsys.json; nothing was built")
        elif built["status"] != "PASS":
            print(f"[run_tests] build failed ({built.get('failure_class')}): {built.get('detail')}  "
                  f"log: {built.get('log')}", file=sys.stderr)
            return EXIT_FAIL
    cache = ResultCache(build_dir / "test-results" / "cache.json")
    jobs, info = plan(args, manifest, build_dir, cache)
    for warning in warnings:
        print(f"[run_tests] WARN {warning}", flush=True)
    if not jobs:
        print(f"[run_tests] nothing to run for tier {args.tier} ({info['scope']} scope, "
              f"{len(info['changed'])} changed path(s))")
    if args.plan:
        total = 0.0
        for job in jobs:
            if job.status == "PENDING":
                total += job.expected
            print(f"{job.status:8s} {job.label:48s} ~{job.expected:6.0f}s  {'; '.join(job.reasons)[:70]}"
                  + (f"  [{job.detail}]" if job.detail else ""))
        # Wall: the parallel phase takes at least its longest job; exclusive
        # jobs run one at a time after it.
        parallel = [j.expected for j in jobs if j.status == "PENDING" and not j.exclusive]
        wall = max(sum(parallel) / max(1, args.jobs), max(parallel, default=0.0)) \
            + sum(j.expected for j in jobs if j.status == "PENDING" and j.exclusive)
        print(f"\nplan: {sum(1 for j in jobs if j.status == 'PENDING')} job(s), ~{total:.0f}s CPU, "
              f"~{wall:.0f}s wall with --jobs {args.jobs}; scope {info['scope']}; "
              f"{len(info['changed'])} changed path(s) ({info['changes_from']})"
              + (f"; unmapped: {', '.join(info['unmapped'][:5])}" if info["unmapped"] else ""))
        return 0

    run_id = f"{time.strftime('%Y%m%dT%H%M%S')}-{os.getpid()}"
    run_dir = scratch_root(run_id)
    run_dir.mkdir(parents=True, exist_ok=True)
    fingerprint = request_fingerprint(Path(args.request)) if args.request else None
    started = time.monotonic()
    print(f"[run_tests] run {run_id}: tier {args.tier}, {info['scope']} scope, "
          f"{sum(1 for j in jobs if j.status == 'PENDING')} job(s) of {len(jobs)}, --jobs {args.jobs}", flush=True)
    # A request-scoped run keeps its owner's claim alive (CI_CD_ROADMAP CON-01)
    # when the caller owns the claim ($AGENT_ID); a stopped run is recorded
    # INTERRUPTED, never PASS.
    heartbeat = contextlib.nullcontext()
    if args.request and os.environ.get("AGENT_ID"):
        import agent_process
        claim = agent_process.read_claim(agent_process.lock_path(ROOT, Path(args.request).name)) or {}
        if claim.get("agent_id") == os.environ["AGENT_ID"]:
            heartbeat = agent_process.Heartbeat(ROOT, Path(args.request).name, os.environ["AGENT_ID"])
    interrupted: list[str] = []

    def _stop(signum, _frame):
        interrupted.append(signal.Signals(signum).name)
        raise KeyboardInterrupt
    previous = {s: signal.signal(s, _stop) for s in (signal.SIGTERM,)}
    try:
        with heartbeat:
            run_pool(jobs, args.jobs, run_dir, verbose=True)
    except KeyboardInterrupt:
        interrupted.append(interrupted[0] if interrupted else "SIGINT")
        kill_running()
        for job in jobs:
            if job.status in ("PENDING",):
                job.status, job.detail = "BLOCKED", "run interrupted before this job finished"
        warnings.append(f"run interrupted ({interrupted[0]}): the classification is INTERRUPTED")
    finally:
        for s, h in previous.items():
            signal.signal(s, h)
    if not args.no_retry:
        for job in jobs:
            if job.status in FAILING and not job.exclusive:
                retry_isolated(job, run_dir)
    today = datetime.now().strftime("%Y-%m-%d")
    entries = load_quarantine()
    for job in jobs:
        apply_quarantine(job, entries, today, warnings)
    wall = time.monotonic() - started
    rows = summarise(jobs)
    classification = "INTERRUPTED" if interrupted else classify(jobs)
    # Cache complete passes only (every shard PASS, nothing flaky / expected).
    at = datetime.now(timezone.utc).isoformat()
    for row in rows:
        group_jobs = [j for j in jobs if j.suite["id"] == row["suite"] and j.group_name == row["group"]]
        key = group_jobs[0].cache_key
        if key and all(j.status == "PASS" for j in group_jobs):
            cache.put(key, {"status": "PASS", "run_id": run_id, "at": at, "suite": row["suite"],
                            "group": row["group"], "seconds": round(row["seconds"], 1)})
    cache.save()
    save_durations(build_dir, jobs)
    record = write_record(build_dir, run_id, args, info, rows, jobs, classification, wall, fingerprint, warnings)
    print_summary(rows, wall, classification, info)
    for warning in warnings:
        print(f"[run_tests] WARN {warning}")
    print(f"record: {record}")
    if args.evidence:
        print("\n" + evidence_markdown(record, rows, classification, wall, info, args, fingerprint))
    if not args.keep:
        for job in jobs:
            if job.status in ("PASS", "CACHED") and job.workdir:
                shutil.rmtree(job.workdir, ignore_errors=True)
        if all(j.status in ("PASS", "CACHED", "PENDING") for j in jobs):
            shutil.rmtree(run_dir, ignore_errors=True)
    if classification == "INTERRUPTED":
        return EXIT_INTERRUPTED
    if classification == "FAIL":
        return EXIT_FAIL
    if classification == "BLOCKED":
        return EXIT_BLOCKED
    if classification == "EMPTY":
        print("[run_tests] EMPTY: nothing was executed and nothing was a cached pass; this run proves nothing",
              file=sys.stderr)
        return EXIT_EMPTY
    return EXIT_PASS


if __name__ == "__main__":
    raise SystemExit(main())
